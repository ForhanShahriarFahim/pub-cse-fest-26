"""Shared helper: Caesar-encrypt a message with key k (letters only, case kept)."""


def encrypt(msg, k):
    out = []
    for ch in msg:
        if "a" <= ch <= "z":
            out.append(chr((ord(ch) - 97 + k) % 26 + 97))
        elif "A" <= ch <= "Z":
            out.append(chr((ord(ch) - 65 + k) % 26 + 65))
        else:
            out.append(ch)
    return "".join(out)
